export function getTrackSpotifyUrl(track) {
  if (track && track.spotifyUrl) return track.spotifyUrl;
  if (!track) return SPOTIFY_PLAYLIST_URL;
  const query = `${track.title} ${track.artist}`.trim();
  return `https://open.spotify.com/search/${encodeURIComponent(query)}`;
}

export function getTrackYouTubeMusicUrl(track) {
  if (track && track.youtubeUrl) return track.youtubeUrl;
  if (track && track.youtubeId) return `https://music.youtube.com/watch?v=${track.youtubeId}`;
  if (!track) return YOUTUBE_PLAYLIST_URL;
  const query = `${track.title} ${track.artist}`.trim();
  return `https://music.youtube.com/search?q=${encodeURIComponent(query)}`;
}

